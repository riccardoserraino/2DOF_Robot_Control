%% PERIODIC MULTISINE DESIGN (frequencies on FFT bins)
% Creates the ms struct and saves it to data/multisine_design.mat
% (also loaded by the InitFcn callback of the Simulink models).
% In Simulink, use a SINGLE Sine Wave block with vector parameters:
%   Amplitude = ms.A   Frequency = ms.w   Phase = ms.phi   Sample time = ms.Ts
% followed by a Sum of Elements block. Changing n_sin here does not require
% any changes to the model.
% No 'clear': the script can be executed from a model callback.

ms.seed   = 30;           % 30 = estimation, 29 = validation experiment
ms.Ts     = 0.002;        % sampling period [s]
ms.Tp     = 8;            % multisine period [s] -> resolution 2*pi/Tp
ms.P      = 6;            % total number of recorded periods
ms.P_skip = 1;            % initial periods to discard (transient)
n_sin     = 10;           % number of sinusoids
w_min     = 5;            % [rad/s]
w_max     = 50;           % [rad/s]

dw       = 2*pi/ms.Tp;                                % fundamental angular frequency
w_target = logspace(log10(w_min), log10(w_max), n_sin);

% k = harmonic index: w_k = k*dw. Integer -> exact period Tp and a point on
% FFT bin k.
% Odd harmonics that are not multiples of previous k values ensure that
% harmonics generated by nonlinearities do not fall on excited frequency bins.
k = zeros(1, n_sin);
for i = 1:n_sin
    ki = round(w_target(i)/dw);
    while mod(ki,2) == 0 || any(k(1:i-1) == ki) || any(mod(ki, k(1:i-1)) == 0)
        ki = ki + 1;
    end
    k(i) = ki;
end

ms.k   = k;
ms.w   = 2*pi*k/ms.Tp;                                % [rad/s]
ms.A   = min(1.5, max(0.4, 0.4*ms.w/30));             % [V], increasing with w
rng(ms.seed);
ms.phi = 2*pi*rand(1, n_sin);                         % [rad]

%% COMPLETE SIGNAL (checks and optional From Workspace input)
t  = (0:ms.Ts:ms.P*ms.Tp)';                           % includes t = P*Tp as in Simulink
u  = sum(ms.A .* sin(ms.w .* t + ms.phi), 2);
ms.tu = [t u];                                        % From Workspace: Data = ms.tu
ms.StopTime = ms.P*ms.Tp;

fprintf('seed = %d, %d sinusoids\n', ms.seed, n_sin)
fprintf('k   = %s\n', mat2str(ms.k))
fprintf('w   = %s rad/s\n', mat2str(round(ms.w,2)))
fprintf('A   = %s V\n', mat2str(round(ms.A,2)))
fprintf('peak |u| = %.2f V, mean over one period = %.1e V\n', ...
        max(abs(u)), mean(u(1:round(ms.Tp/ms.Ts))))
fprintf('Simulink stop time = %g s\n', ms.StopTime)

save('../../data/multisine_design.mat', '-struct', 'ms');     % fields saved as variables (Tp, k, ...)

% Remove temporaries: only ms stays in the workspace
clear dw w_target k i ki t u n_sin w_min w_max

